def _launch_main() -> None:
    """启动正式后端控制台（main.py）。"""
    print("  正在启动正式后端控制台...\n")
    try:
        main_path = ROOT / "main.py"
        subprocess.Popen(
            [sys.executable, str(main_path)],
            cwd=str(ROOT),
            stdin=sys.stdin,
            stdout=sys.stdout,
            stderr=sys.stderr,
        )
    except Exception as e:
        print(f"  启动失败: {e}")
        print("  请手动运行: python main.py")


if __name__ == "__main__":
    success = run()
    sys.exit(0 if success else 1)
