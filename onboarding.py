    for m in pkgs["missing"][:5]:
        print(f"    - {m}")
    if len(pkgs["missing"]) > 5:
        print(f"    ... 还有 {len(pkgs['missing']) - 5} 个")

    install = _safe_input("\n  是否安装缺失依赖? (Y/n)", default="Y").lower()
