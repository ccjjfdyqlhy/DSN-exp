def _load_existing_env() -> dict[str, str]:
    env = {}
    if ENV_PATH.exists():
        with open(ENV_PATH, "r", encoding="utf-8") as f:
            for line in f:
                stripped = line.strip()
                if not stripped or stripped.startswith("#"):
                    continue
                if "=" in stripped:
                    k, v = stripped.split("=", 1)
                    env[k.strip()] = v.strip()
    return env


def _env_write(key: str, value: str) -> None:
    lines: list[str] = []
    found = False
    if ENV_PATH.exists():
        with open(ENV_PATH, "r", encoding="utf-8") as f:
            for line in f:
                stripped = line.lstrip()
                if stripped.startswith("#") or stripped == "":
                    lines.append(line)
                    continue
                if "=" in stripped:
                    k = stripped.split("=", 1)[0].strip()
                    if k.upper() == key.upper():
                        lines.append(f"{key}={value}\n")
                        found = True
                        continue
                lines.append(line)
    else:
        lines.append("# DSN-exp .env (auto-generated by onboarding)\n")
    if not found:
        lines.append(f"{key}={value}\n")
    with open(ENV_PATH, "w", encoding="utf-8") as f:
        f.writelines(lines)


def _env_read(key: str) -> str:
    env = _load_existing_env()
    return env.get(key, env.get(key.upper(), ""))


def _is_configured() -> bool:
    if not ENV_PATH.exists():
        return False
    env = _load_existing_env()
    key = env.get("OPENAI_API_KEY", "")
    return bool(key and key != "sk-your-key-here")


def _run_shell(cmd: str, timeout: int = 30) -> dict:
    try:
        result = subprocess.run(
            cmd, shell=True, capture_output=True, text=True, timeout=timeout,
            cwd=str(ROOT),
        )
        return {
            "success": result.returncode == 0,
            "output": result.stdout.strip(),
            "error": result.stderr.strip(),
            "exit_code": result.returncode,
        }
    except subprocess.TimeoutExpired:
        return {"success": False, "output": "", "error": "命令超时", "exit_code": -1}
    except Exception as e:
        return {"success": False, "output": "", "error": str(e), "exit_code": -1}


def _run_python(code: str, timeout: int = 30) -> dict:
    import tempfile
    tmp = tempfile.NamedTemporaryFile(mode="w", suffix=".py", delete=False, encoding="utf-8")
    try:
        tmp.write(code)
        tmp.close()
        result = _run_shell(f'"{sys.executable}" "{tmp.name}"', timeout=timeout)
        return result
    finally:
        try:
            os.unlink(tmp.name)
        except Exception:
            _log.warning("Operation failed", exc_info=True)


