def _check_python() -> dict:
    ver = sys.version_info
    return {
        "version": f"{ver.major}.{ver.minor}.{ver.micro}",
        "executable": sys.executable,
        "ok": ver >= (3, 10),
    }


def _check_conda() -> dict:
    r = _run_shell("conda --version 2>/dev/null || echo NOT_FOUND")
    if "NOT_FOUND" in r["output"]:
        return {"available": False, "version": ""}
    return {"available": True, "version": r["output"].strip()}


def _check_pip_packages() -> dict:
    import importlib.metadata

    req_path = ROOT / "requirements.txt"
    if not req_path.exists():
        return {"all_ok": True, "missing": [], "errors": []}

    required = {}
    with open(req_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            m = re.match(r"^([A-Za-z0-9_\-]+)", line)
            if m:
                required[m.group(1).lower()] = line

    missing = []
    errors = []
    for pkg_name, req_line in required.items():
        try:
            importlib.metadata.version(pkg_name)
        except importlib.metadata.PackageNotFoundError:
            missing.append(req_line)
        except Exception as e:
            errors.append(f"{pkg_name}: {e}")

    return {"all_ok": len(missing) == 0 and len(errors) == 0, "missing": missing, "errors": errors}


def _probe_service(base_url: str, path: str = "", timeout: float = 3.0) -> bool:
    """
    用 requests 探测服务是否可达。
    与运行时探活一致：status < 500 视为可达（服务在运行），
    避免 GPT-SoVITS 根路径返回 404/405 被误判为未运行。
    """
    url = f"{base_url.rstrip('/')}{path}"
    try:
        resp = requests.get(url, timeout=timeout)
        return resp.status_code < 500
    except Exception:
        return False


